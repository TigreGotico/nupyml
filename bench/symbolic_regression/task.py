"""Symbolic regression: recover a compact FORMULA from data.

The target is generated by a nonlinear closed-form expression of a few variables.
A method that can compose operators (genetic programming) can recover the formula
and generalise; a fixed-basis regressor must approximate it. Scored by held-out R².
"""
import numpy as np

from nupyml.metrics import r2_score

KIND = "supervised"
GOAL = "Recover a nonlinear formula y=f(x); scored by held-out R^2."
METRIC = "r2"
HIGHER_IS_BETTER = True
MIN_SCORE = 0.80


def load():
    rng = np.random.RandomState(0)
    X = rng.uniform(-2, 2, (600, 3))
    # a genuine closed-form target with interaction + nonlinearity
    y = X[:, 0] ** 2 + 2 * X[:, 0] * X[:, 1] - np.sin(X[:, 2]) + 0.05 * rng.randn(600)
    n_tr = int(0.7 * len(y))
    return X[:n_tr], y[:n_tr], X[n_tr:], y[n_tr:]


def metric(y_true, y_pred):
    return r2_score(y_true, y_pred)
