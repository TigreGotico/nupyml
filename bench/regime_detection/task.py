"""Regime detection: segment a series into its hidden states.

A one-dimensional series is generated by switching between two REGIMES with different
means and volatilities (a Markov-switching process). Each timestep is described by
rolling statistics (its value, and the local mean and standard deviation), and the
task is to cluster the timesteps back into the regime that generated them -- without
labels. Scored by the adjusted Rand index against the true regime sequence.
"""
import numpy as np

from nupyml.metrics import adjusted_rand_score

KIND = "clustering"
GOAL = "Cluster timesteps into their generating regime; adjusted Rand index."
METRIC = "adjusted_rand"
HIGHER_IS_BETTER = True
MIN_SCORE = 0.3


def load():
    rng = np.random.RandomState(0)
    n = 400
    # two regimes: (low mean, low vol) and (high mean, high vol), persistent
    regime = np.zeros(n, int)
    for t in range(1, n):
        regime[t] = regime[t - 1] if rng.rand() < 0.97 else 1 - regime[t - 1]
    y = np.where(regime == 0, rng.randn(n) * 0.3 - 1.0, rng.randn(n) * 1.0 + 1.5)
    w = 10
    val = y
    roll_mean = np.array([y[max(0, t - w):t + 1].mean() for t in range(n)])
    roll_std = np.array([y[max(0, t - w):t + 1].std() for t in range(n)])
    X = np.column_stack([val, roll_mean, roll_std])
    return X, regime


def metric(y_true, y_pred):
    return float(adjusted_rand_score(y_true, y_pred))
